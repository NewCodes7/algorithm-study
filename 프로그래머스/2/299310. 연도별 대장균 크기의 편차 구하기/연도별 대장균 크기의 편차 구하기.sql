WITH MAX_SIZE AS (SELECT YEAR(DIFFERENTIATION_DATE) AS YEAR, MAX(SIZE_OF_COLONY) AS SIZE
FROM ECOLI_DATA
GROUP BY YEAR(DIFFERENTIATION_DATE))
SELECT B.YEAR, (B.SIZE - A.SIZE_OF_COLONY) AS YEAR_DEV, A.ID
FROM ECOLI_DATA A LEFT JOIN MAX_SIZE B ON YEAR(DIFFERENTIATION_DATE) = B.YEAR
ORDER BY B.YEAR, YEAR_DEV

